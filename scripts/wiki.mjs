// ---------------------------------------------------------------------------
{
  const lines = [
    '# Mechanics',
    '',
    'The mechanic tag is the reason this library exists.',
    '',
    'Plenty of places will tell you what somebody built. Almost nowhere tells you **what decided',
    'whether it worked** — and that is the part that transfers between domains. A distribution gap',
    'kills an on-chain launch and a developer tool in exactly the same way.',
    '',
    'So "show me everything that died of a distribution gap" is a question this library can answer',
    'and most cannot.',
    '',
  ];
  for (const m of tax.raw.tags.mechanic) {
    const hits = ideas.filter((i) => (i.tags ?? []).includes(m.id));
    lines.push(`## \`${m.id}\``, '', `*${m.definition}*`, '');
    if (hits.length) {
      for (const i of hits) lines.push(`- ${ideaLink(i)} — \`${i.outcome}\``);
    } else {
      lines.push('_No idea carries this tag yet._');
    }
    lines.push('');
  }
  page('Mechanics', lines);
}

// ---------------------------------------------------------------------------
{
  const lines = ['# Catalog', '', `Every idea in the library. Generated — see [Home](Home).`, ''];
  for (const c of tax.categories) {
    const rows = ideas.filter((i) => i.category === c.id);
    if (!rows.length) continue;
    lines.push(`## ${c.label}`, '', `*${c.definition}*`, '',
      '| Idea | Outcome | Effort | Why |', '|---|---|---|---|');
    for (const i of rows) {
      lines.push(`| ${ideaLink(i)} | \`${i.outcome}\` | ${i.effort} | ${String(i.verdict).replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
  }
  page('Catalog', lines);
}


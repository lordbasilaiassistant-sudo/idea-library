  '',
  '## Roles',
  '',
  '| Role | Mandate | Cadence |',
  '|---|---|---|',
  '| `bot:digger` | Take the next pending dig, extract ideas, one PR per batch | daily |',
  '| `bot:rater` | Score unscored ideas on the public rubric. Never rates its own | daily |',
  '| `bot:dissenter` | For any idea scoring above threshold, argue the opposite case | daily |',
  '| `bot:verifier` | Re-run reusable snippets, check links, confirm evidence exists, downgrade `confidence` on rot | weekly |',
  '| `bot:librarian` | Dedupe near-identical ideas, fix tags, propose taxonomy additions | weekly |',
  '| `bot:groundskeeper` | Rebuild generated files, prune dead links, report coverage | daily |',

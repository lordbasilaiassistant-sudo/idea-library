#!/usr/bin/env node
/**
 * wiki.mjs — generate the GitHub wiki from the same data as everything else.
 *
 *   node scripts/wiki.mjs --out <path-to-cloned-wiki>
 *
 * A wiki maintained by hand rots faster than any other surface, because nothing
 * fails when it goes stale. So the reference pages (schema, taxonomy, outcomes,
 * the catalog) are generated from data/taxonomy.json and the idea files, exactly
 * like index.json is. Regenerate and push; never edit a generated page in the
 * browser.
 *
 * Pages whose content is genuinely prose — the security model, the bot protocol —
 * are written here as source, so that this script remains the one place the wiki
 * comes from.
 */

import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadIdeas, loadTaxonomy, loadSources, readJSON } from './lib/ideas.mjs';

const args = new Map();
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  if (argv[i].startsWith('--')) args.set(argv[i].slice(2), argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : 'true');
}

const OUT = args.get('out');
if (!OUT) {
  console.error('usage: node scripts/wiki.mjs --out <path to cloned .wiki repo>');
  process.exit(1);
}
if (!existsSync(OUT)) {
  console.error(`wiki: ${OUT} does not exist. Clone the wiki first:`);
  console.error('  git clone https://github.com/lordbasilaiassistant-sudo/idea-library.wiki.git');
  process.exit(1);
}

const tax = loadTaxonomy();
const sources = loadSources();
const site = readJSON('data/site.json');
const ideas = loadIdeas().filter((i) => !i._error);
const REPO = site.repo;
const BANNER = '<!-- GENERATED by scripts/wiki.mjs in the main repo. Do not edit here; your change will be overwritten. -->';

const pages = {};
const page = (name, lines) => { pages[name] = [BANNER, '', ...lines, ''].join('\n'); };
const ideaLink = (i) => `[${i.title}](${REPO}/tree/main/ideas/${i.category}/${i.id})`;

